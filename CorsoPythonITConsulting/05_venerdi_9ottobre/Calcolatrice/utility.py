# 4 operazioni per la calcolatrice e mi sfrutto queste funzioni poi nel menu

def somma (a, b):
    return a + b

def sottrai (a, b):
    return a - b

def moltiplica (a, b):
    return a * b

def dividi(a, b):
    if b == 0:
        print("Impossibile dividere per zero!")
    else:
        return a / b

